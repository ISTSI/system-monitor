"""Reproduce the browser casefold table from the locked Python 3.13 runtime."""

import argparse
import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "frontend/src/unicodeCasefold.ts"


def generated() -> str:
    if sys.version_info[:2] != (3, 13):
        raise RuntimeError("Generate casefold data with the locked Python 3.13 runtime.")
    table = {
        chr(code): chr(code).casefold()
        for code in range(sys.maxunicode + 1)
        if chr(code).casefold() != chr(code)
    }
    return (
        "// Generated by scripts/generate_casefold.py from Python's Unicode database.\n"
        "// License notices: public/licenses/unicode-license.txt and python-license.txt.\n"
        "// Do not substitute browser lowercasing or locale-sensitive comparisons.\n"
        f"export const CASEFOLD_UNICODE_VERSION = {json.dumps(unicodedata.unidata_version)};\n"
        f"export const CASEFOLD_PYTHON_VERSION = {json.dumps('.'.join(map(str, sys.version_info[:3])))};\n"
        "export const CASEFOLD: Readonly<Record<string, string>> = "
        + json.dumps(table, ensure_ascii=True, separators=(",", ":"))
        + ";\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generated()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text("utf-8") != text:
            print("Browser casefold data differs from the locked Python runtime.")
            return 1
        print("Browser casefold data matches the locked Python runtime.")
    else:
        OUTPUT.write_text(text, encoding="utf-8")
        print("Generated the browser Unicode casefold table.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
